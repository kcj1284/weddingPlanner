// Requires Playwright: npm install --no-save playwright, then npx playwright install chromium.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.CHEONGMO_URL || 'http://localhost:8080';
async function waitFor(page, predicate) { await page.waitForFunction(predicate); }
(async () => {
  fs.mkdirSync('artifacts', { recursive: true });
  const browser = await chromium.launch({ headless: true, ...(process.env.CHEONGMO_BROWSER ? { executablePath: process.env.CHEONGMO_BROWSER } : {}) });
  const errors = [];
  const hostContext = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const guestContext = await browser.newContext({ viewport: { width: 390, height: 844 }, timezoneId: 'America/New_York' });
  const host = await hostContext.newPage(), guest = await guestContext.newPage();
  [host, guest].forEach(p => p.on('pageerror', e => errors.push(e.message)));
  try {
    await host.goto(base); await host.locator('[data-action="demo-host"]').waitFor();
    await guest.goto(base); await guest.locator('[data-action="demo-guest"]').waitFor();
    await guest.screenshot({ path: 'artifacts/mobile-welcome.png', fullPage: true });
    await host.locator('[data-action="demo-host"]').click();
    await host.locator('[data-tab="manage"]').waitFor();
    await guest.locator('[data-action="demo-guest"]').click();
    await guest.locator('#vote-form').waitFor();
    assert.equal(await guest.locator('[data-tab="manage"]').count(), 0);
    assert.equal(await guest.locator('[data-tab="places"]').count(), 0);
    await host.locator('[data-action="new"]').first().click();
    const title = '브라우저 검증 ' + Date.now();
    await host.locator('#new-form [name="title"]').fill(title);
    await host.locator('#new-form [name="area"]').fill('서울 성수');
    await host.locator('#new-form [name="expectedCount"]').fill('4');
    await host.locator('#new-form button[type="submit"]').click();
    await host.locator('#meeting-detail h2').filter({ hasText: title }).waitFor();
    await host.locator('[data-action="add-time"]').click();
    await host.locator('#option-form [name="title"]').fill('2026-11-01T18:30');
    await host.locator('#option-form button[type="submit"]').click();
    await waitFor(host, () => !document.querySelector('#modal').open);
    await host.locator('[data-action="add-place"]').click();
    await host.locator('#option-form [name="title"]').fill('검증용 식당');
    await host.locator('#option-form [name="detail"]').fill('실제 업소가 아닌 테스트 후보');
    await host.locator('#option-form button[type="submit"]').click();
    await waitFor(host, () => !document.querySelector('#modal').open);
    await host.locator('[data-action="share"]').click();
    await host.locator('#guest-link-form [name="label"]').fill('브라우저 검증 친구');
    await host.locator('#guest-link-form button[type="submit"]').click();
    const invite = await host.locator('#invite-link').inputValue();
    await host.locator('#close-modal').click();
    await guest.goto(invite);
    await guest.locator('#guest-form').waitFor();
    await guest.locator('#guest-form [name="displayName"]').fill('브라우저 게스트');
    await guest.locator('#guest-form button[type="submit"]').click();
    await guest.locator('#meeting-detail h2').filter({ hasText: title }).waitFor();
    for (const checkbox of await guest.locator('#vote-form input[type="checkbox"]').all()) await checkbox.check();
    await guest.locator('#vote-form button[type="submit"]').click();
    await guest.locator('#toast').filter({ hasText: '나의 투표를 저장했어요.' }).waitFor();
    await host.locator('[data-action="refresh"]').click();
    await host.locator('.votes-count').filter({ hasText: '1명 선택' }).first().waitFor();
    const meetingId = new URL(guest.url()).searchParams.get('meeting');
    const noCsrf = await guestContext.request.put(base + '/api/meetings/' + meetingId + '/votes', { data: { optionIds: [] } });
    assert.equal(noCsrf.status(), 403);
    const guestSearch = await guestContext.request.get(base + '/api/meetings/' + meetingId + '/places?q=성수&type=FD6');
    assert.equal(guestSearch.status(), 403);
    await host.locator('[data-tab="places"]').click();
    await host.locator('#search-form button[type="submit"]').click();
    await host.locator('#search-results .hint').waitFor();
    assert.match(await host.locator('#search-results').innerText(), /직접 추가/);
    await host.locator('[data-tab="manage"]').click();
    await host.locator('[data-action="reservation"]').click();
    await host.locator('#reservation-form [name="status"]').selectOption('BOOKED');
    await host.locator('#reservation-form [name="note"]').fill('테스트 예약 확인');
    await host.locator('#reservation-form button[type="submit"]').click();
    await waitFor(host, () => !document.querySelector('#modal').open);
    await host.locator('#confirm-form [name="timeId"]').selectOption({ index: 1 });
    await host.locator('#confirm-form [name="placeId"]').selectOption({ index: 1 });
    await host.locator('#confirm-form button[type="submit"]').click();
    await host.locator('.confirmed').waitFor();
    await guest.locator('[data-action="refresh"]').click();
    await guest.locator('.confirmed').waitFor();
    assert.match(await guest.locator('.confirmed').innerText(), /18:30/);
    assert.equal(await guest.locator('#vote-form input:enabled').count(), 0);
    assert.match(await guest.locator('.confirmed').innerText(), /예약 완료/);
    for (const width of [360, 390, 768, 1280]) {
      await host.setViewportSize({ width, height: 900 });
      const size = await host.evaluate(() => ({ scroll: document.documentElement.scrollWidth, view: innerWidth }));
      assert.ok(size.scroll <= size.view, 'horizontal overflow at ' + width + ': ' + JSON.stringify(size));
    }
    await host.setViewportSize({ width: 1280, height: 900 });
    await host.evaluate(() => { document.querySelector('#toast').classList.remove('visible'); window.scrollTo({top:0,behavior:'instant'}); });
    await guest.evaluate(() => { document.querySelector('#toast').classList.remove('visible'); window.scrollTo({top:0,behavior:'instant'}); });
    await host.screenshot({ path: 'artifacts/desktop-host.png', fullPage: true });
    await guest.screenshot({ path: 'artifacts/mobile-guest.png', fullPage: true });
    await host.locator('[data-action="reopen"]').click();
    await host.locator('[data-action="reopen-confirm"]').click();
    await host.locator('#vote-form button[type="submit"]').waitFor();
    await guest.locator('[data-action="refresh"]').click();
    for (const checkbox of await guest.locator('#vote-form input[type="checkbox"]').all()) await checkbox.uncheck();
    await guest.locator('#vote-form button[type="submit"]').click();
    await guest.locator('#toast').filter({ hasText: '나의 투표를 저장했어요.' }).waitFor();
    assert.equal(await guest.locator('#vote-form input:checked').count(), 0);
    // This check leaves its explicitly named test meeting in the local development database.
    await guest.locator('[data-action="logout"]').click();
    await guest.locator('[data-action="signup"]').first().waitFor();
    assert.equal((await guestContext.request.get(base+'/api/meetings')).status(),401);
    await guest.locator('[data-action="signup"]').first().click();
    await guest.locator('#auth-form [name="username"]').fill('check_' + Date.now());
    await guest.locator('#auth-form [name="displayName"]').fill('가입 검증');
    await guest.locator('#auth-form [name="password"]').fill('browser-password123');
    await guest.locator('#auth-form button[type="submit"]').focus();
    await guest.keyboard.press('Enter');
    await guest.locator('.intro-head h1').filter({hasText:'가입 검증님의 청모'}).waitFor();
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ result: 'PASS', meetingId, checks: ['host/guest separation', 'create and invite', 'candidates and vote', 'CSRF enforcement', 'guest search denied', 'search fallback', 'reservation record', 'confirm and freeze', 'reopen and withdraw', '360/390/768/1280 no overflow', 'no JavaScript page errors'], screenshots: ['mobile-welcome.png', 'desktop-host.png', 'mobile-guest.png'] }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
